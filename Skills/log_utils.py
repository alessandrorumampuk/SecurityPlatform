"""
Centralized logging utility - Single Source of Truth for all vulnerability
scan outputs across Skills/ (broken_access_control, broken_link_hijacking,
xss, etc).

All scripts write their scan output to SecurityPlatform/log/ using a standard
filename format instead of scattering results into per-category log/
subfolders. This makes it trivial to find "what was the latest XSS scan"
or "what was the latest broken-link scan" regardless of which script
category produced it.

Filename format:
    yyyymmdd-hhmmss-{vulnerability_name}.{extension}

Example:
    20260831-153000-broken_link_hijacking.json
    20260831-153512-xss.html
"""

import os
from datetime import datetime

SKILLS_DIR = os.path.dirname(os.path.abspath(__file__))
LOG_DIR = os.path.join(os.path.dirname(SKILLS_DIR), "log")


def _slugify(name: str) -> str:
    """Normalize a vulnerability name into a safe filename component."""
    return name.strip().lower().replace(" ", "_")


def new_log_path(vulnerability_name: str, extension: str = "json") -> str:
    """
    Build a new, timestamped log file path under the centralized log/
    directory: log/yyyymmdd-hhmmss-{vulnerability_name}.{extension}

    Creates the log directory if it doesn't exist yet.
    """
    os.makedirs(LOG_DIR, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    extension = extension.lstrip(".")
    filename = f"{timestamp}-{_slugify(vulnerability_name)}.{extension}"
    return os.path.join(LOG_DIR, filename)


def latest_log_path(vulnerability_name: str, extension: str = "json"):
    """
    Find the most recently generated log file for `vulnerability_name` in
    the centralized log/ directory. Returns None if none exist yet.
    """
    if not os.path.isdir(LOG_DIR):
        return None
    extension = extension.lstrip(".")
    suffix = f"-{_slugify(vulnerability_name)}.{extension}"
    matches = [f for f in os.listdir(LOG_DIR) if f.endswith(suffix)]
    if not matches:
        return None
    # Filenames start with yyyymmdd-hhmmss, so a plain sort is chronological.
    matches.sort(reverse=True)
    return os.path.join(LOG_DIR, matches[0])


def generated_by_comment(script_name: str) -> str:
    """Human-readable provenance string to embed in log output."""
    return f"Generated by {script_name} on {datetime.now().isoformat()}"
